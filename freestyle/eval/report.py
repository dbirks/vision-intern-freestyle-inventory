"""Merge many ``runs/*/metrics.json`` files into a Markdown results table."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Mapping, Sequence


def load_run_metrics(paths: Sequence[str | Path]) -> list[dict[str, Any]]:
    """Load metrics dictionaries from JSON files, tagging fallback experiment names."""
    runs: list[dict[str, Any]] = []
    for raw_path in paths:
        path = Path(raw_path)
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        if not data.get("experiment"):
            data["experiment"] = path.parent.name or path.stem
        data.setdefault("_source_path", str(path))
        runs.append(data)
    return runs


def _fmt_cell(val: float | None, ci: Sequence[float] | None = None, *, digits: int = 3) -> str:
    if val is None:
        return "-"
    text = f"{val:.{digits}f}"
    if ci is not None and len(ci) == 2:
        text += f" ({ci[0]:.{digits}f}–{ci[1]:.{digits}f})"
    return text


def _sort_key(run: Mapping[str, Any], sort_by: str) -> tuple[Any, ...]:
    if sort_by == "experiment":
        return (str(run.get("experiment", "")),)
    loc = run.get("localization", {})
    if sort_by == "ap50":
        val = loc.get("ap50")
        return (-(float(val) if val is not None else -1.0), str(run.get("experiment", "")))
    if sort_by == "ap50_95":
        val = loc.get("ap50_95")
        return (-(float(val) if val is not None else -1.0), str(run.get("experiment", "")))
    raise ValueError(f"Unsupported sort_by={sort_by!r}; expected 'experiment', 'ap50', or 'ap50_95'.")


def render_markdown_table(
    runs: Sequence[Mapping[str, Any]],
    *,
    sort_by: str = "ap50",
) -> str:
    """Render a GitHub-flavored Markdown comparison table from metrics dicts."""
    headers = [
        "Experiment",
        "Thr",
        "AP50 (95% CI)",
        "AP50:95 (95% CI)",
        "P / R / F1",
        "ID Top-1 (95% CI)",
        "ID Macro-F1",
        "Total MAE",
        "Class MAE",
        "Exact Inv",
        "Imgs (Grps)",
        "s/img",
    ]
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join(["---"] * len(headers)) + " |",
    ]

    for run in sorted(runs, key=lambda r: _sort_key(r, sort_by)):
        loc = run.get("localization", {})
        ident = run.get("identification", {})
        cnt = run.get("counting", {})
        cis = run.get("bootstrap_ci95", {}).get("metrics", {})
        meta = run.get("meta", {}) if isinstance(run.get("meta"), Mapping) else {}

        exp = str(run.get("experiment", "unknown"))
        thr = run.get("score_thr")
        thr_str = f"{thr:.2f}" if isinstance(thr, (int, float)) else "-"
        p_r_f1 = (
            f"{_fmt_cell(loc.get('precision'))} / "
            f"{_fmt_cell(loc.get('recall'))} / "
            f"{_fmt_cell(loc.get('f1'))}"
        )
        sec = meta.get("seconds_per_image")
        sec_str = f"{float(sec):.2f}" if isinstance(sec, (int, float)) else "-"
        imgs_grps = f"{run.get('n_images', '-')} ({run.get('n_groups', '-')})"

        row = [
            f"`{exp}`",
            thr_str,
            _fmt_cell(loc.get("ap50"), cis.get("localization.ap50")),
            _fmt_cell(loc.get("ap50_95"), cis.get("localization.ap50_95")),
            p_r_f1,
            _fmt_cell(ident.get("top1_acc"), cis.get("identification.top1_acc")),
            _fmt_cell(ident.get("macro_f1")),
            _fmt_cell(cnt.get("total_count_mae")),
            _fmt_cell(cnt.get("per_class_count_mae")),
            _fmt_cell(cnt.get("exact_inventory_rate")),
            imgs_grps,
            sec_str,
        ]
        lines.append("| " + " | ".join(row) + " |")

    return "\n".join(lines)


def build_results_markdown(
    runs: Sequence[Mapping[str, Any]],
    *,
    sort_by: str = "ap50",
) -> str:
    """Build the full ``docs/freestyle/RESULTS.md`` document."""
    lines = [
        "<!-- Generated by freestyle/eval/report.py; do not hand-edit. -->",
        "# Freestyle Cartridge Recognition — Experiment Results",
        "",
    ]
    if not runs:
        lines.append("_No experiment `metrics.json` files found._")
    else:
        lines.append(render_markdown_table(runs, sort_by=sort_by))
    lines.append("")
    return "\n".join(lines)


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Merge runs/*/metrics.json into a Markdown table.")
    p.add_argument(
        "inputs",
        nargs="*",
        help="Optional paths to metrics.json files (defaults to <runs-dir>/*/metrics.json).",
    )
    p.add_argument("--runs-dir", default="runs", help="Directory to scan when inputs are omitted.")
    p.add_argument("--out", default=None, help="Output Markdown path (prints to stdout if omitted).")
    p.add_argument(
        "--sort-by",
        choices=("ap50", "ap50_95", "experiment"),
        default="ap50",
        help="Row sort key (default ap50).",
    )
    return p


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)

    if args.inputs:
        paths = [Path(p) for p in args.inputs]
    else:
        paths = sorted(Path(args.runs_dir).glob("*/metrics.json"))

    runs = load_run_metrics(paths)
    md = build_results_markdown(runs, sort_by=args.sort_by)

    if args.out:
        out_path = Path(args.out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(md)
    else:
        print(md, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
